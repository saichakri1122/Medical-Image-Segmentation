class DoubleConv(nn.Module):
    def __init__(self, in_c, out_c):
        super(DoubleConv, self).__init__()
        self.conv = nn.Sequential(
            nn.Conv2d(in_c, out_c, 3, padding=1),
            nn.ReLU(inplace=True),
            nn.Conv2d(out_c, out_c, 3, padding=1),
            nn.ReLU(inplace=True)
        )

    def forward(self, x):
        return self.conv(x)

class UNet(nn.Module):
    def __init__(self):
        super(UNet, self).__init__()
        self.dconv1 = DoubleConv(1, 64)
        self.dconv2 = DoubleConv(64, 128)
        self.dconv3 = DoubleConv(128, 256)
        self.dconv4 = DoubleConv(256, 512)

        self.maxpool = nn.MaxPool2d(2)
        self.upsample = nn.ConvTranspose2d(512, 512, 2, stride=2)

        self.uconv3 = DoubleConv(512 + 256, 256)
        self.uconv2 = DoubleConv(256 + 128, 128)
        self.uconv1 = DoubleConv(128 + 64, 64)

        self.final = nn.Conv2d(64, 1, 1)

    def forward(self, x):
        # Encoder
        c1 = self.dconv1(x)
        c2 = self.dconv2(self.maxpool(c1))
        c3 = self.dconv3(self.maxpool(c2))
        c4 = self.dconv4(self.maxpool(c3))

        # Decoder
        u3 = self.upsample(c4)
        u3 = torch.cat([u3, c3], dim=1)
        u3 = self.uconv3(u3)

        u2 = F.interpolate(u3, scale_factor=2, mode='bilinear', align_corners=True)
        u2 = torch.cat([u2, c2], dim=1)
        u2 = self.uconv2(u2)

        u1 = F.interpolate(u2, scale_factor=2, mode='bilinear', align_corners=True)
        u1 = torch.cat([u1, c1], dim=1)
        u1 = self.uconv1(u1)

        out = self.final(u1)
        return torch.sigmoid(out)

